#!/usr/bin/env python3
"""Exactness + TTFT test of prefix_cache on the bare engine (one process, one LLM).

    SM120_MOE_IMPL=torch PYTHONPATH=/opt/sm120/sm120:/work/deepinfer_pc DEEPINFER_ROOT=/work/deepinfer_pc \
      python3 /opt/sm120/tests/test_prefix_cache.py --ckpt /work/ckpt3 [--json /work/pc_test.json]

For every case, prompt A = P[:X] + a, prompt B = P[:X] + b (shared prefix X), or B = A + c (multi-turn). B runs:
  nocache : cache off, no forced chunking                      (the plain engine)
  chunked : cache off, prefill split where the hit will split  (same chunk boundaries as the hit run)
  cached  : A first (records snapshots), then B (hit at the longest cached k <= len(B) - 2)
Compared: the logits DeepInfer samples from (prefill last position + every decode step, sm120_capture) and the greedy
tokens. PASS = cached is bit-identical to chunked. cached vs nocache is reported too (chunked prefill itself
may round differently from one-pass prefill). Needs a deterministic MoE (SM120_MOE_IMPL=torch); b12x fused_moe
differs run to run. TTFT: a long shared prefix, B with and without a hit (min over repeats).
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "prefix_cache"))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "tools"))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", default="/work/ckpt3")
    ap.add_argument("--decode", type=int, default=8)
    ap.add_argument("--max-num-seqs", type=int, default=4)
    ap.add_argument("--max-num-batched-tokens", type=int, default=4096)
    ap.add_argument("--gpu-memory-utilization", type=float, default=0.90)
    ap.add_argument("--ttft-prefix", type=int, default=2000)
    ap.add_argument("--json", default=None)
    ap.add_argument("--cases", default="all")
    ap.add_argument("--grain", type=int, default=128)
    ap.add_argument("--nextn", type=int, default=0, help="MTP draft tokens (needs mtp.* layers, e.g. ckpt_full)")
    ap.add_argument("--snapshot-prompt-end", choices=("auto", "1", "0"), default="auto")
    ap.add_argument("--gen", type=int, default=24, help="tokens generated by A in the generation-end cases")
    args = ap.parse_args()

    import argparse as _ap

    import numpy as np

    import run_deepinfer

    run_deepinfer.setup_env(_ap.Namespace(max_blocks=256, zos="default", batch_invariant=False, nextn=args.nextn, graphs=False,
                                          force_topk=None, deepinfer_root=os.environ.get("DEEPINFER_ROOT", "/opt/deepinfer")))
    os.environ.setdefault("DEEPINFER_PREFILL_ATTEMPT_INTERVAL", "1")
    import prefix_cache

    prefix_cache.configure_env(args.max_num_seqs, 64)
    import sm120_patches

    sm120_patches.install()
    from _config import create_llm

    import torch

    import sm120_capture
    from deepinfer.sampling_params import SamplingParams

    llm = create_llm(args.ckpt, 0, ep_size=1, cp_size=1, data_parallel_size=1,
                     max_num_batched_tokens=args.max_num_batched_tokens, max_model_len=16384,
                     max_num_seqs=args.max_num_seqs, gpu_memory_utilization=args.gpu_memory_utilization,
                     lookahead_tokens=min(1, args.nextn), disable_log_stats=True)
    eng = llm.llm_engine
    spe = None if args.snapshot_prompt_end == "auto" else args.snapshot_prompt_end == "1"
    pc = prefix_cache.install(eng, grain=args.grain, max_entries=64, nextn=args.nextn, snapshot_prompt_end=spe)
    rng = np.random.default_rng(7)
    P = rng.integers(1000, 100000, size=8192).tolist()

    def gen(ids, n=args.decode):
        """-> (tokens, [logit rows]) for one prompt: prefill-sampled row + one row per decode step."""
        sm120_capture.arm(len(ids), keep_full_prefill=False)
        out = llm.generate(prompt_token_ids=[ids], sampling_params=SamplingParams(
            temperature=0.0, max_tokens=n, ignore_eos=True, seq_seed=0), use_tqdm=False)
        torch.cuda.synchronize()
        sm120_capture.disarm()
        st = sm120_capture.STATE
        rows = [t[-1] for t in st["prefill_sampled"][-1:]] + [r[0] for r in sm120_capture.decode_rows()[: n - 1]]
        return [int(x.token_id) for x in out[0]], rows

    def mode(lookup, snapshot, checkpoints, extra=()):
        pc.lookup, pc.snapshot, pc.checkpoints = lookup, snapshot, checkpoints
        pc.extra_checkpoints = list(extra)

    def cmp(r1, r2):
        if len(r1) != len(r2):
            return dict(equal=False, n=f"{len(r1)} vs {len(r2)}")
        eq = all(torch.equal(a, b) for a, b in zip(r1, r2))
        md = max(float((a.float() - b.float()).abs().max()) for a, b in zip(r1, r2)) if r1 else 0.0
        cos = min(float(torch.nn.functional.cosine_similarity(a.float(), b.float(), dim=0)) for a, b in zip(r1, r2)) if r1 else 1.0
        top1 = sum(int(a.argmax() == b.argmax()) for a, b in zip(r1, r2)) / max(1, len(r1))
        return dict(equal=eq, max_abs=round(md, 4), min_cos=round(cos, 6), top1=round(top1, 3))

    cases = []
    for X in (127, 128, 129, 255, 256, 257, 300, 383, 384, 385, 640):
        cases.append(dict(name=f"shared X={X}", A=P[:X] + P[5000:5040], B=P[:X] + P[6000:6060]))
    for LA in (128, 200, 333, 511):  # multi-turn: B extends A; hit at the prompt-end snapshot of A
        A = P[:LA]
        cases.append(dict(name=f"extend LA={LA}", A=A, B=A + P[7000:7037]))
    for X in (200, 333):  # generation end: B = A + A's answer + new turn; hit at the snapshot taken when A finished
        cases.append(dict(name=f"gen-end LA={X}", A=P[:X], gen=True))
    if args.cases != "all":
        cases = [c for c in cases if any(s in c["name"] for s in args.cases.split(","))]

    results, n_fail = [], 0

    def gen_end_case(c):
        """A generates; B = A + its answer + 30 new tokens. The answer's KV came from decode steps in the cached run and
        from a prefill chunk in the baselines, so the comparison is rounding-level (cos / top-1 / tokens), not bitwise."""
        A = c["A"]
        mode(True, True, True)
        pc.clear()
        tA, _ = gen(A, args.gen)
        ks = sorted(e.k for e in pc.entries.values() if e.k > len(A))
        k_gen = ks[-1] if ks else 0
        B = A + tA + P[8000:8030]
        ok_prefix = k_gen > 0 and k_gen <= len(A) + len(tA)
        h0 = pc.stats["hits"]
        t_ca, r_ca = gen(B)
        hit = pc.stats["hits"] - h0
        hit_k = max((e.k for e in pc.entries.values() if e.hits), default=0)
        mode(False, False, True, extra=[k_gen] if k_gen else [])
        t_ch, r_ch = gen(B)
        mode(False, False, False)
        t_nc, r_nc = gen(B)
        vs_ch, vs_nc = cmp(r_ch, r_ca), cmp(r_nc, r_ca)
        ok = bool(hit) and ok_prefix and hit_k == k_gen and vs_ch["top1"] == 1.0 and vs_ch["min_cos"] > 0.98
        res = dict(case=c["name"], len_A=len(A), gen=len(tA), len_B=len(B), hit=bool(hit), k=hit_k, gen_end_k=k_gen,
                   cached_vs_chunked=vs_ch, cached_vs_nocache=vs_nc, tokens_eq_chunked=t_ca == t_ch,
                   tokens_eq_nocache=t_ca == t_nc, ok=ok)
        print(f"[{'PASS' if ok else 'FAIL'}] {c['name']:16s} lenA {len(A):4d} +{len(tA)} gen, lenB {len(B):4d} hit k={hit_k:4d} "
              f"(gen-end snapshot k {k_gen}) | cached vs chunked {vs_ch} tokens {t_ca == t_ch} | cached vs nocache "
              f"{vs_nc} tokens {t_ca == t_nc}", flush=True)
        return res
    for c in cases:
        if c.get("gen"):
            results.append(gen_end_case(c))
            n_fail += not results[-1]["ok"]
            continue
        A, B = c["A"], c["B"]
        # where the hit will be: the longest snapshot of A (multiples of 128 < len(A), and len(A)) that B shares
        G = args.grain
        ends = [len(A)] if pc.snapshot_prompt_end else []
        cands = [k for k in list(range(G, len(A), G)) + ends if k <= len(B) - 2 and A[:k] == B[:k]]
        k_exp = max(cands) if cands else 0
        pc.clear()
        mode(False, False, False)
        t_nc, r_nc = gen(B)
        mode(False, False, True, extra=[k_exp] if k_exp else [])
        t_ch, r_ch = gen(B)
        mode(True, True, True)
        pc.clear()
        gen(A)
        h0 = pc.stats["hits"]
        t_ca, r_ca = gen(B)
        hit = pc.stats["hits"] - h0
        k_hit = k_exp if hit else 0
        vs_ch, vs_nc = cmp(r_ch, r_ca), cmp(r_nc, r_ca)
        ok = vs_ch["equal"] and t_ca == t_ch and (hit == 1) == (k_exp > 0)
        n_fail += not ok
        res = dict(case=c["name"], len_A=len(A), len_B=len(B), hit=bool(hit), k=k_hit, expected_k=k_exp,
                   cached_eq_chunked=vs_ch, cached_eq_nocache=vs_nc, tokens_eq_chunked=t_ca == t_ch,
                   tokens_eq_nocache=t_ca == t_nc, chunked_eq_nocache=cmp(r_nc, r_ch)["equal"], ok=ok)
        results.append(res)
        print(f"[{'PASS' if ok else 'FAIL'}] {c['name']:16s} lenA {len(A):4d} lenB {len(B):4d} hit k={k_hit:4d} "
              f"(exp {k_exp:4d}) | cached==chunked {vs_ch} | cached vs nocache {vs_nc} tokens {t_ca == t_nc} | "
              f"chunked==nocache {res['chunked_eq_nocache']}", flush=True)

    # TTFT: long shared prefix (multiple of 128) + short suffix, max_tokens=1
    mode(True, True, True)
    pc.clear()
    X = (args.ttft_prefix // 128) * 128
    A = P[:X] + P[7500:7520]
    gen(A, 1)
    t_hit, t_miss, t_plain = [], [], []
    for r in range(3):
        B = P[:X] + P[7600 + 40 * r: 7630 + 40 * r]
        t0 = time.perf_counter()
        gen(B, 1)
        t_hit.append(time.perf_counter() - t0)
        Bm = P[4000:4000 + X] + P[7600 + 40 * r: 7630 + 40 * r]  # same length, unseen prefix
        mode(False, True, True)
        t0 = time.perf_counter()
        gen(Bm, 1)
        t_miss.append(time.perf_counter() - t0)
        mode(False, False, False)  # the plain engine: no cache, no forced chunks
        Bp = P[2000:2000 + X] + P[7600 + 40 * r: 7630 + 40 * r]
        t0 = time.perf_counter()
        gen(Bp, 1)
        t_plain.append(time.perf_counter() - t0)
        mode(True, True, True)
    ttft = dict(prefix=X, suffix=30, grain=args.grain, hit_s=min(t_hit), miss_s=min(t_miss), plain_s=min(t_plain),
                speedup_vs_miss=min(t_miss) / min(t_hit), speedup_vs_plain=min(t_plain) / min(t_hit),
                all_hit=t_hit, all_miss=t_miss, all_plain=t_plain)
    print(f"[TTFT] prefix {X} + 30 new tokens (grain {args.grain}): plain engine {ttft['plain_s']:.3f}s  cache miss "
          f"{ttft['miss_s']:.3f}s  cache hit {ttft['hit_s']:.3f}s  (x{ttft['speedup_vs_plain']:.1f} vs plain)", flush=True)
    print("[STATS]", json.dumps(pc.summary()))
    print(f"{len(results) - n_fail}/{len(results)} cases passed")
    if args.json:
        json.dump(dict(results=results, ttft=ttft, stats=pc.summary(), ckpt=args.ckpt,
                       env={k: v for k, v in os.environ.items() if k.startswith(("SM120_", "DEEPINFER_"))}),
                  open(args.json, "w"), indent=1, default=str)
    llm.close()
    return 1 if n_fail else 0


if __name__ == "__main__":
    sys.exit(main())
